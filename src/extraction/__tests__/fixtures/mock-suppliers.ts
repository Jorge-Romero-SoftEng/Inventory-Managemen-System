import type { Availability, StandardExtractedProduct } from "@/types/supplier";

/**
 * Mock supplier dataset used to stress-test the extraction pipeline.
 *
 * Ten fictional Argentine wholesale suppliers, each rendered in the four
 * input formats the pipeline accepts (WhatsApp text, Excel rows, PDF lines,
 * Google Sheets rows + URL). Four suppliers are "clean" (structured, dated,
 * consistent ARS prices) and six are "messy" (greetings, abbreviations,
 * mixed currency symbols, missing prices/units, out-of-stock markers, price
 * update announcements, omitted effective dates).
 *
 * `expected` holds the normalized JSON that the pipeline should persist for
 * each supplier, following the standard extraction schema. The raw
 * representations intentionally deviate from `expected` in the messy
 * fixtures — that divergence is exactly what the AI extraction step is
 * supposed to resolve.
 *
 * The Excel/Sheets 2D arrays mirror the row layout that SheetJS
 * (`header: 1, raw: false`) produces, and the PDF lines mirror what
 * pdf-parse v2 returns, so any representation can be fed directly into the
 * real extractors or pasted into the extraction UI for manual testing.
 */

export interface GoogleSheetsFixture {
  url: string;
  rows: string[][];
}

/** Ground-truth normalized output (effective_date may be null when the source omits it). */
export interface ExpectedExtraction {
  supplier: string;
  effective_date: string | null;
  products: StandardExtractedProduct[];
}

export interface MockSupplierFixture {
  id: string;
  name: string;
  profile: "clean" | "messy";
  whatsapp: string;
  excel: string[][];
  pdf: string[];
  googleSheets: GoogleSheetsFixture;
  expected: ExpectedExtraction;
}

type ProductSeed = [
  name: string,
  unit: string,
  price: number | null,
  availability?: Availability,
  currency?: string | null,
];

/** Formats a price using Argentine conventions ("1.250,50"), like the raw documents. */
function priceToEsAr(n: number | null): string {
  if (n === null) return "";
  return n.toLocaleString("es-AR", { minimumFractionDigits: 0, maximumFractionDigits: 2 });
}

function toExpected(supplier: string, effectiveDate: string | null, seeds: ProductSeed[]): ExpectedExtraction {
  return {
    supplier,
    effective_date: effectiveDate,
    products: seeds.map(([name, unit, price, availability = "available", currency = "ARS"]) => ({
      name,
      unit,
      price,
      currency,
      availability,
    })),
  };
}

function tableRows(seeds: ProductSeed[]): string[][] {
  return seeds.map(([name, unit, price, , currency]) => [
    name,
    unit,
    price === null ? "" : `${currency === "USD" ? "U$S " : "$"}${priceToEsAr(price)}`,
    "Disponible",
  ]);
}

